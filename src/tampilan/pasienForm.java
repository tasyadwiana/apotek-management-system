    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed

        try {
            Connection conn = Koneksi.getConnection();
            String sql = "INSERT INTO pasien VALUES (?, ?, ?, ?, ?, ?)";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, txtId.getText());
            ps.setString(2, txtNama.getText());
            ps.setString(3, txtAlamat.getText());
            ps.setString(4, txtNoHP.getText());
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            ps.setString(5, sdf.format(TanggalLahir.getDate()));
            ps.setString(6, cmbGender.getSelectedItem().toString());

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data berhasil disimpan!");
            kosong();
            loadDataPasien();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
        }

    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed

        try {
            Connection conn = Koneksi.getConnection();
            String sql = "UPDATE pasien SET nama=?, alamat=?, no_hp=?, tgl_lahir=?, jenis_kelamin=? WHERE id_pasien=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, txtNama.getText());
            ps.setString(2, txtAlamat.getText());
            ps.setString(3, txtNoHP.getText());
            Date selectedDate = (Date) TanggalLahir.getDate();
            if (selectedDate == null) {
            JOptionPane.showMessageDialog(this, "Tanggal lahir belum dipilih!");
             return;
            }
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            ps.setString(4, sdf.format(selectedDate));

            ps.setString(5, cmbGender.getSelectedItem().toString());
            ps.setString(6, txtId.getText());

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data berhasil diubah!");
            kosong();
            loadDataPasien();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal edit data: " + e.getMessage());
        }

    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed

        int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                Connection conn = Koneksi.getConnection();
                String sql = "DELETE FROM pasien WHERE id_pasien=?";
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setString(1, txtId.getText());
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
                kosong();
                loadDataPasien();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal hapus data: " + e.getMessage());
            }
        }

    }//GEN-LAST:event_btnHapusActionPerformed

    private void tabelPasienMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelPasienMouseClicked

        int baris = tabelPasien.getSelectedRow();
        if (baris != -1) {
            txtId.setText(tabelPasien.getValueAt(baris, 0).toString());
            txtNama.setText(tabelPasien.getValueAt(baris, 1).toString());
            txtAlamat.setText(tabelPasien.getValueAt(baris, 2).toString());
            txtNoHP.setText(tabelPasien.getValueAt(baris, 3).toString());
            String tglStr = tabelPasien.getValueAt(baris, 4).toString();
if (tglStr != null && !tglStr.isEmpty()) {
    try {
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        Date date = sdf.parse(tglStr); 
        TanggalLahir.setDate(date);
    } catch (ParseException e) {
        e.printStackTrace(); 
        TanggalLahir.setDate(null);
    }
} else {
    TanggalLahir.setDate(null);
}


            cmbGender.setSelectedItem(tabelPasien.getValueAt(baris, 5).toString());
        }

    }//GEN-LAST:event_tabelPasienMouseClicked

