      private void loadDataPasien() {
     Object[] Baris ={"ID","Nama","Alamat","No HP","Tanggal Lahir","Jenis Kelamin"}; 
           DefaultTableModel model = new DefaultTableModel(null, Baris); 

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT * FROM pasien";
        java.sql.Statement stat = conn.createStatement(); 
        ResultSet rs = stat.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString(1),
                rs.getString(2),
                rs.getString(3),
                rs.getString(4),
                rs.getString(5),
                rs.getString(6)
            });
        }

        tabelPasien.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load data: " + e.getMessage());
    }

    }
      
      private void cariDataPasien(String keyword) {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("Nama");
    model.addColumn("Alamat");
    model.addColumn("No HP");
    model.addColumn("Tanggal Lahir");
    model.addColumn("Jenis Kelamin");

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT * FROM pasien WHERE "
                   + "id_pasien LIKE ? OR "
                   + "nama LIKE ? OR "
                   + "alamat LIKE ? OR "
                   + "no_hp LIKE ? OR "
                   + "tgl_lahir LIKE ? OR "
                   + "jenis_kelamin LIKE ?";
        PreparedStatement ps = conn.prepareStatement(sql);
        for (int i = 1; i <= 6; i++) {
            ps.setString(i, "%" + keyword + "%");
        }

        ResultSet rs = ps.executeQuery();
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("id_pasien"),
                rs.getString("nama"),
                rs.getString("alamat"),
                rs.getString("no_hp"),
                rs.getString("tgl_lahir"),
                rs.getString("jenis_kelamin")
            });
        }

        tabelPasien.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal mencari data: " + e.getMessage());
    }
}
      

