    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try {
            Connection conn = Koneksi.getConnection();
            String sql = "INSERT INTO obat (id_obat, nama_obat, stok, harga_jual, harga_beli, tanggal_expired, id_supplier) VALUES (?, ?, ?, ?, ?, ?, ?)";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, txtIdObat.getText());
            ps.setString(2, txtNamaObat.getText());
            int stok = Integer.parseInt(txtStok.getText());
            ps.setInt(3, stok);
            ps.setDouble(4, Double.parseDouble(txtHargaJual.getText()));
            ps.setString(5, txtHargaBeli.getText());
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            ps.setString(6, sdf.format(tanggalExpired.getDate()));
            String idSupplier = cmbSupplier.getSelectedItem().toString().split(" - ")[0];
            ps.setString(7, idSupplier);
            
            ps.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Data obat berhasil disimpan!");
            loadDataObat();
            kosong();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage());
        }

    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed

    try {
        Connection conn = Koneksi.getConnection();
       String sql = "UPDATE obat SET nama_obat=?, stok=?, harga_jual=?, harga_beli=?, tanggal_expired=?, id_supplier=? WHERE id_obat=?";
        PreparedStatement ps = conn.prepareStatement(sql);

        ps.setString(1, txtNamaObat.getText());
        int stok = Integer.parseInt(txtStok.getText());
        ps.setInt(2, stok);
        ps.setString(3, txtHargaJual.getText());
        ps.setString(4, txtHargaBeli.getText());

        Date selectedDate = (Date) tanggalExpired.getDate();
        if (selectedDate == null) {
            JOptionPane.showMessageDialog(this, "Tanggal expired belum dipilih!");
            return;
        }
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        ps.setString(5, sdf.format(selectedDate));

        // Ambil id_supplier dari combo box
        String selectedSupplier = (String) cmbSupplier.getSelectedItem();
        String idSupplier = selectedSupplier.split(" - ")[0]; // Ambil hanya ID-nya saja
        ps.setString(6, idSupplier);

        ps.setString(7, txtIdObat.getText());

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data berhasil diubah!");
        loadDataObat();
        kosong();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal edit data: " + e.getMessage());
    }


    }//GEN-LAST:event_btnEditActionPerformed

