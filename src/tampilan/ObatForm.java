      private void loadDataObat() {
     Object[] Baris ={"ID","Nama","Stok","Harga Jual","Harga Beli","Expired","Supplier"}; 
           DefaultTableModel model = new DefaultTableModel(null, Baris); 

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT o.id_obat, o.nama_obat, o.stok, o.harga_jual, o.harga_beli, o.tanggal_expired, s.nama_supplier " +
                     "FROM obat o JOIN supplier s ON o.id_supplier = s.id_supplier";
        java.sql.Statement stat = conn.createStatement(); 
        ResultSet rs = stat.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString(1),
                rs.getString(2),
                rs.getString(3),
                rs.getString(4),
                rs.getString(5),
                rs.getString(6),
                rs.getString(7)
            });
        }

        tableObat.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load data: " + e.getMessage());
    }
      }
      
     private void cariDataObat(String keyword) {
    Object[] Baris = {"ID", "Nama Obat", "Stok", "Harga Jual", "Harga Beli", "Expired", "Supplier"}; 
    DefaultTableModel model = new DefaultTableModel(null, Baris);

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT o.id_obat, o.nama_obat, o.stok, o.harga_jual, o.harga_beli, "
                   + "o.tanggal_expired, s.nama_supplier "
                   + "FROM obat AS o JOIN supplier AS s ON o.id_supplier = s.id_supplier "
                   + "WHERE o.id_obat LIKE ? OR "
                   + "o.nama_obat LIKE ? OR "
                   + "o.stok LIKE ? OR "
                   + "o.harga_jual LIKE ? OR "
                   + "o.harga_beli LIKE ? OR "
                   + "o.tanggal_expired LIKE ? OR "
                   + "s.nama_supplier LIKE ?";

        PreparedStatement ps = conn.prepareStatement(sql);
        for (int i = 1; i <= 7; i++) {
            ps.setString(i, "%" + keyword + "%");
        }

        ResultSet rs = ps.executeQuery();
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("id_obat"),
                rs.getString("nama_obat"),
                rs.getString("stok"),
                rs.getString("harga_jual"),
                rs.getString("harga_beli"),
                rs.getString("tanggal_expired"),
                rs.getString("nama_supplier")
            });
        }

        tableObat.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal mencari data: " + e.getMessage());
    }
}

