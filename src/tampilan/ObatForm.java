 private void loadSupplier() {
    try {
        Connection conn = Koneksi.getConnection();
        java.sql.Statement stat = conn.createStatement(); 
        ResultSet rs = stat.executeQuery("SELECT id_supplier, nama_supplier FROM supplier");
        cmbSupplier.removeAllItems();
        while (rs.next()) {
            cmbSupplier.addItem(rs.getString("id_supplier") + " - " + rs.getString("nama_supplier"));
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load supplier: " + e.getMessage());
    }
}
 
 private void cekObatAkanExpired() {
    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT nama_obat, tanggal_expired FROM obat WHERE tanggal_expired <= DATE_ADD(CURDATE(), INTERVAL 3 MONTH)";
        PreparedStatement ps = conn.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        StringBuilder pesan = new StringBuilder();
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

        while (rs.next()) {
            String namaObat = rs.getString("nama_obat");
            String tanggalExpired = rs.getString("tanggal_expired");
            pesan.append("Obat: ").append(namaObat)
                 .append(" akan expired pada: ").append(tanggalExpired).append("\n");
        }

        if (pesan.length() > 0) {
            JOptionPane.showMessageDialog(this,
                "Perhatian! Ada obat yang akan kedaluwarsa dalam 3 bulan:\n\n" + pesan.toString(),
                "Notifikasi Expired", JOptionPane.WARNING_MESSAGE);
        }

        rs.close();
        ps.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal mengecek obat yang akan expired: " + e.getMessage());
    }
}

