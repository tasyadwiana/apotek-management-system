    private void loadDataKunjungan() {
    DefaultTableModel model = new DefaultTableModel(new String[]{"ID", "Pasien", "Tanggal", "Keluhan"}, 0);
    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT k.id_kunjungan, p.nama, k.tanggal, k.keluhan FROM kunjungan k JOIN pasien p ON k.id_pasien = p.id_pasien";
        java.sql.Statement stat = conn.createStatement();
        ResultSet rs = stat.executeQuery(sql);
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("id_kunjungan"),
                rs.getString("nama"),
                rs.getString("tanggal"),
                rs.getString("keluhan")
            });
        }
        tabelKunjungan.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load data: " + e.getMessage());
    }
}   

     private void cariDataKunjungan(String keyword) {
     Object[] Baris = {"ID", "Pasien", "Tanggal", "Keluhan"}; 
    DefaultTableModel model = new DefaultTableModel(null, Baris); 

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT k.id_kunjungan, p.nama, k.tanggal, k.keluhan " +
                     "FROM kunjungan k " +
                     "JOIN pasien p ON k.id_pasien = p.id_pasien " +
                     "WHERE k.id_kunjungan LIKE ? OR p.nama LIKE ? OR k.tanggal LIKE ? OR k.keluhan LIKE ?";
        PreparedStatement ps = conn.prepareStatement(sql);
        String likeKeyword = "%" + keyword + "%";
        ps.setString(1, likeKeyword);
        ps.setString(2, likeKeyword);
        ps.setString(3, likeKeyword);
        ps.setString(4, likeKeyword);
        ResultSet rs = ps.executeQuery();
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("id_kunjungan"),
                rs.getString("nama"),
                rs.getString("tanggal"),
                rs.getString("keluhan")
            });
        }

        tabelKunjungan.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal mencari data: " + e.getMessage());
    }
}
