    private void loadPasien() {
    try {
        Connection conn = Koneksi.getConnection();
        java.sql.Statement stat = conn.createStatement(); 
        ResultSet rs = stat.executeQuery("SELECT id_pasien, nama FROM pasien");
        cmbPasien.removeAllItems();
        while (rs.next()) {
            cmbPasien.addItem(rs.getString("id_pasien") + " - " + rs.getString("nama"));
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load pasien: " + e.getMessage());
    }
}

