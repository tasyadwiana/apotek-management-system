    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
    try {
        Connection conn = Koneksi.getConnection();
        String sql = "UPDATE kunjungan SET id_pasien=?, tanggal=?, keluhan=? WHERE id_kunjungan=?";
        PreparedStatement ps = conn.prepareStatement(sql);
        String idPasien = cmbPasien.getSelectedItem().toString().split(" - ")[0];
        ps.setString(1, idPasien);
        Date selectedDate = tanggalKunjungan.getDate();
            if (selectedDate == null) {
            JOptionPane.showMessageDialog(this, "Tanggal lahir belum dipilih!");
             return;
            }
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            ps.setString(2, sdf.format(selectedDate));
            
        ps.setString(3, txtKeluhan.getText());
        ps.setString(4, txtIdKunjungan.getText());
        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data berhasil diubah");
        loadDataKunjungan();
        kosong();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal edit: " + e.getMessage());
    }
    }//GEN-LAST:event_btnEditActionPerformed

