    private void tabelKunjunganMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelKunjunganMouseClicked
   
    int row = tabelKunjungan.getSelectedRow();
    txtIdKunjungan.setText(tabelKunjungan.getValueAt(row, 0).toString());
    
    
    String namaPasienDariTabel = tabelKunjungan.getValueAt(row, 1).toString();


    for (int i = 0; i < cmbPasien.getItemCount(); i++) {
        String item = cmbPasien.getItemAt(i);
        if (item.contains(" - " + namaPasienDariTabel)) {
            cmbPasien.setSelectedIndex(i);
            break;
        }
    }

    String tglStr = tabelKunjungan.getValueAt(row, 2).toString();
    if (tglStr != null && !tglStr.isEmpty()) {
        try {
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            Date date = sdf.parse(tglStr);
            tanggalKunjungan.setDate(date);
        } catch (ParseException e) {
            e.printStackTrace(); 
            tanggalKunjungan.setDate(null);
        }
    } else {
        tanggalKunjungan.setDate(null);
    }
    txtKeluhan.setText(tabelKunjungan.getValueAt(row, 3).toString());


    }//GEN-LAST:event_tabelKunjunganMouseClicked

