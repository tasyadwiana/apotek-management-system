    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "INSERT INTO pegawai (nama_pegawai, jenis_kelamin, no_telp, alamat, jabatan) VALUES (?, ?, ?, ?, ?)";
        PreparedStatement ps = conn.prepareStatement(sql);

        ps.setString(1, txtNama.getText());
        ps.setString(2, cmbGender.getSelectedItem().toString());
        ps.setString(3, txtTelp.getText());
        ps.setString(4, txtAlamat.getText());
        ps.setString(5, txtJabatan.getText());

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data pegawai berhasil disimpan");
        loadDataPegawai();
        kosong();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal simpan: " + e.getMessage());
    }


    }//GEN-LAST:event_btnSimpanActionPerformed

