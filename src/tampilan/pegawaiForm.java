    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
    try {
        int row = tabelPegawai.getSelectedRow();
        String id = tabelPegawai.getValueAt(row, 0).toString();

        Connection conn = Koneksi.getConnection();
        String sql = "UPDATE pegawai SET nama_pegawai=?, jenis_kelamin=?, no_telp=?, alamat=?, jabatan=? WHERE id_pegawai=?";
        PreparedStatement ps = conn.prepareStatement(sql);

        ps.setString(1, txtNama.getText());
        ps.setString(2, cmbGender.getSelectedItem().toString());
        ps.setString(3, txtTelp.getText());
        ps.setString(4, txtAlamat.getText());
        ps.setString(5, txtJabatan.getText());
        ps.setString(6, id);

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data pegawai berhasil diupdate");
        loadDataPegawai();
        kosong();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal update: " + e.getMessage());
    }


    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
    try {
        int row = tabelPegawai.getSelectedRow();
        String id = tabelPegawai.getValueAt(row, 0).toString();

        Connection conn = Koneksi.getConnection();
        String sql = "DELETE FROM pegawai WHERE id_pegawai=?";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, id);
        ps.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data pegawai berhasil dihapus");
        loadDataPegawai();
        kosong();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal hapus: " + e.getMessage());
    }


    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
                                         
    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT * FROM pegawai WHERE id_pegawai LIKE ? OR nama_pegawai LIKE ? OR jenis_kelamin LIKE ? OR no_telp LIKE ? OR alamat LIKE ? OR jabatan LIKE ?";
        PreparedStatement ps = conn.prepareStatement(sql);

        String keyword = "%" + txtCari.getText() + "%"; // Mengambil input dari field pencarian
        ps.setString(1, keyword);
        ps.setString(2, keyword);
        ps.setString(3, keyword);
        ps.setString(4, keyword);
        ps.setString(5, keyword);
        ps.setString(6, keyword);
        

        ResultSet rs = ps.executeQuery();

        DefaultTableModel model = (DefaultTableModel) tabelPegawai.getModel();
        model.setRowCount(0); 

        while (rs.next()) {
            Object[] row = {
                rs.getInt("id_pegawai"), 
                rs.getString("nama_pegawai"),
                rs.getString("jenis_kelamin"),
                rs.getString("no_telp"),
                rs.getString("alamat"),
                rs.getString("jabatan")
            };
            model.addRow(row);
        }

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Data tidak ditemukan.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal mencari: " + e.getMessage());
    }

    }//GEN-LAST:event_btnCariActionPerformed

    private void loadDataPegawai() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("Nama");
    model.addColumn("Gender");
    model.addColumn("No. Telp");
    model.addColumn("Alamat");
    model.addColumn("Jabatan");

    try {
        Connection conn = Koneksi.getConnection();
        String sql = "SELECT * FROM pegawai";
        java.sql.Statement stat = conn.createStatement(); 
        ResultSet rs = stat.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id_pegawai"),
                rs.getString("nama_pegawai"),
                rs.getString("jenis_kelamin"),
                rs.getString("no_telp"),
                rs.getString("alamat"),
                rs.getString("jabatan")
            });
        }
        tabelPegawai.setModel(model);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal tampilkan data: " + e.getMessage());
    }
}

