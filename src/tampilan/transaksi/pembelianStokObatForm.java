    private void btnsimpantransaksiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsimpantransaksiActionPerformed
    try {
        Connection conn = Koneksi.getConnection();
        DefaultTableModel model = (DefaultTableModel) tabelObat.getModel();

        // Ambil tanggal dari JDateChooser
        java.util.Date utilDate = dateTanggal.getDate();
        if (utilDate == null) {
            JOptionPane.showMessageDialog(this, "Tanggal belum diisi.");
            return;
        }
        java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());

        // Ambil ID dari ComboBox Supplier dan Pegawai
        String idSupplier = cmbSupplier.getSelectedItem().toString().split(" - ")[0];
        String idPegawai = cmbPegawai.getSelectedItem().toString().split(" - ")[0];

        // INSERT ke tabel pembelian (tanpa input id_pembelian, karena auto increment)
        String insertPembelian = "INSERT INTO pembelian (tanggal, id_supplier, id_pegawai, total) VALUES (?, ?, ?, ?)";
        PreparedStatement psPembelian = conn.prepareStatement(insertPembelian, Statement.RETURN_GENERATED_KEYS);
        psPembelian.setDate(1, sqlDate);
        psPembelian.setString(2, idSupplier);
        psPembelian.setString(3, idPegawai);
        psPembelian.setDouble(4, hitungTotal());
        if (tabelObat.getRowCount() == 0) {
        JOptionPane.showMessageDialog(null, "Gagal menyimpan! Harap isi tabel dengan data transaksi.");
        return;
        }
        
        psPembelian.executeUpdate();

        // Ambil id_pembelian terakhir yang barusan disimpan
        ResultSet generatedKeys = psPembelian.getGeneratedKeys();
        int idPembelian = -1;
        if (generatedKeys.next()) {
            idPembelian = generatedKeys.getInt(1);
        } else {
            JOptionPane.showMessageDialog(this, "Gagal mendapatkan ID pembelian.");
            return;
        }

        // Simpan data dari JTable ke tabel detail_pembelian
        for (int i = 0; i < model.getRowCount(); i++) {
            String idObat = model.getValueAt(i, 1).toString().trim();;  // kolom ke-1 = id_obat
            double harga = Double.parseDouble(model.getValueAt(i, 3).toString());
            int jumlah = Integer.parseInt(model.getValueAt(i, 4).toString());
            double subtotal = Double.parseDouble(model.getValueAt(i, 5).toString());

            String insertDetail = "INSERT INTO detail_pembelian (id_pembelian, id_obat, harga, jumlah, subtotal) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement psDetail = conn.prepareStatement(insertDetail);
            psDetail.setInt(1, idPembelian);
            psDetail.setString(2, idObat);
            psDetail.setDouble(3, harga);
            psDetail.setInt(4, jumlah);
                psDetail.setDouble(5, subtotal);
            psDetail.executeUpdate();
             String updateStok = "UPDATE obat SET stok = stok + ? WHERE id_obat = ?";
            PreparedStatement psUpdateStok = conn.prepareStatement(updateStok);
            psUpdateStok.setInt(1, jumlah);
            psUpdateStok.setString(2, idObat);
            psUpdateStok.executeUpdate();

        }
        

        JOptionPane.showMessageDialog(this, "Data pembelian berhasil disimpan!");
        

        // Kosongkan tabel dan form
        model.setRowCount(0);
        txtTotal.setText("");
        clearForm();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage());
        e.printStackTrace();
    }

    }//GEN-LAST:event_btnsimpantransaksiActionPerformed

