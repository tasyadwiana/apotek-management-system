    private void cmbobatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbobatActionPerformed
                                        
    try {
        Object selectedObj = cmbobat.getSelectedItem();
        if (selectedObj != null) {
            String selected = selectedObj.toString();
            int id_obat = Integer.parseInt(selected.split(" - ")[0]);
            
            Connection conn = Koneksi.getConnection();
            PreparedStatement ps = conn.prepareStatement("SELECT harga_beli FROM obat WHERE id_obat=?");
            ps.setInt(1, id_obat);
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {
                txtharga.setText(String.valueOf(rs.getDouble("harga_beli")));
            }
        } else {
            // Optional: kosongkan harga kalau tidak ada yang dipilih
            txtharga.setText("");
        }
    } catch (Exception e) {
        e.printStackTrace();
    }


    }//GEN-LAST:event_cmbobatActionPerformed

