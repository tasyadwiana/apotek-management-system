private double hitungTotal() {
    double total = 0;
    for (int i = 0; i < tabelObat.getRowCount(); i++) {
        total += (double) tabelObat.getValueAt(i, 5); // Kolom Subtotal
    }
    lblTotal.setText("Total: Rp " + total);
    return total;
}

  private int getTotalFromTable() {
    int total = 0;
    DefaultTableModel model = (DefaultTableModel) tabelObat.getModel();
    int rowCount = model.getRowCount();
    
    for (int i = 0; i < rowCount; i++) {
        int subtotal = Integer.parseInt(model.getValueAt(i,3).toString().split("\\.")[0]);
        total += subtotal;
    }

    return total;
}

private void ambilHargaObat() {
    try {
        if (cmbobat.getSelectedItem() == null) return;

        String selected = cmbobat.getSelectedItem().toString();
        String kodeObat = selected.split(" - ")[0];

        Connection conn = koneksi.Koneksi.getConnection();
        PreparedStatement ps = conn.prepareStatement("SELECT harga_beli FROM obat WHERE id_obat = ?");
        ps.setString(1, kodeObat);

        ResultSet rs = ps.executeQuery();
        if (rs.next()) {
            double harga = rs.getDouble("harga_beli");
            txtharga.setText(String.valueOf(harga));
        }

        rs.close();
        ps.close();
        conn.close(); // Tutup koneksi DI SINI SAJA
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal ambil harga: " + e.getMessage());
    }
}

