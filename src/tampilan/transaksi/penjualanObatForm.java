    private void cmbObatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbObatActionPerformed

    try {
        String selected = cmbObat.getSelectedItem().toString();
        int id_obat = Integer.parseInt(selected.split(" - ")[0]);
        Connection conn = Koneksi.getConnection();
        PreparedStatement ps = conn.prepareStatement("SELECT harga_jual FROM obat WHERE id_obat=?");
        ps.setInt(1, id_obat);
        ResultSet rs = ps.executeQuery();
        if (rs.next()) {
            txtHarga.setText(String.valueOf(rs.getDouble("harga_jual")));
        }
    } catch (Exception e) {
        e.printStackTrace();
    }


    }//GEN-LAST:event_cmbObatActionPerformed

