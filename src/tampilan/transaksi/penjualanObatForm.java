    private void btnSimpanTransaksiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanTransaksiActionPerformed

    try {
        Connection conn = Koneksi.getConnection();
        conn.setAutoCommit(false);

        // Simpan header
        String pasien = cmbPasien.getSelectedItem().toString();
        String id_pasien = pasien.split(" - ")[0];
        int id_pegawai = Integer.parseInt(cmbPegawai.getSelectedItem().toString().split(" - ")[0]); // Ganti sesuai sesi login
        // Date tanggal = new java.sql.Date(dateChooser == null ? null : dateChooser.getDate().getTime());
        
        PreparedStatement ps = conn.prepareStatement(
            "INSERT INTO penjualan (tanggal, id_pasien, id_pegawai, total) VALUES (?, ?, ?, ?)",
            Statement.RETURN_GENERATED_KEYS);
        ps.setDate(1, new java.sql.Date(System.currentTimeMillis()));
        ps.setString(2, id_pasien);
        ps.setInt(3, id_pegawai);
        ps.setDouble(4, getTotalFromTable());
        if (tablePenjualan.getRowCount() == 0) {
        JOptionPane.showMessageDialog(null, "Gagal menyimpan! Harap isi tabel dengan data transaksi.");
        return;
        }

        ps.executeUpdate();

        ResultSet rs = ps.getGeneratedKeys();
        int id_penjualan = 0;
        if (rs.next()) {
            id_penjualan = rs.getInt(1);
        }

        // Simpan detail
        for (int i = 0; i < tablePenjualan.getRowCount(); i++) {
            String obatStr = tablePenjualan.getValueAt(i, 0).toString();
            int id_obat = Integer.parseInt(obatStr.split(" - ")[0]);
            double harga = (double) tablePenjualan.getValueAt(i, 1);
            int jumlah = (int) tablePenjualan.getValueAt(i, 2);
            double subtotal = (double) tablePenjualan.getValueAt(i, 3);

            PreparedStatement psDetail = conn.prepareStatement(
            "INSERT INTO detail_penjualan (id_penjualan, id_obat, jumlah, harga, subtotal) VALUES (?, ?, ?, ?, ?)");
            psDetail.setInt(1, id_penjualan);
            psDetail.setInt(2, id_obat);
            psDetail.setInt(3, jumlah);
            psDetail.setDouble(4, harga);
            psDetail.setDouble(5, subtotal);
            psDetail.executeUpdate();

            // Kurangi stok obat
            PreparedStatement psUpdateStok = conn.prepareStatement(
                "UPDATE obat SET stok = stok - ? WHERE id_obat = ?");
            psUpdateStok.setInt(1, jumlah);
            psUpdateStok.setInt(2, id_obat);
            psUpdateStok.executeUpdate();
        }

        conn.commit();
        JOptionPane.showMessageDialog(null, "Transaksi berhasil disimpan");
        kosong();
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Gagal menyimpan transaksi" + e.getMessage());
    }


    }//GEN-LAST:event_btnSimpanTransaksiActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
                                       
    if (selectedRow != -1) {
        DefaultTableModel model = (DefaultTableModel) tablePenjualan.getModel();
        model.removeRow(selectedRow); // Hapus baris
        selectedRow = -1; // Reset setelah dihapus
        hitungTotal(); // Panggil fungsi hitung ulang total jika ada
    } else {
        JOptionPane.showMessageDialog(this, "Pilih baris yang ingin dihapus!");
    }


    }//GEN-LAST:event_btnHapusActionPerformed

